#!/usr/bin/env python3
"""Parse System32/winmm.dll PE32+ export table and emit winmm_exports.inc, winmm_stubs.S, and winmm.def."""
import os
import struct
import sys


def rva_to_off(sections, rva):
    for va, vsize, raw_size, raw_ptr in sections:
        span = max(vsize, raw_size)
        if va <= rva < va + span:
            return raw_ptr + (rva - va)
    raise ValueError(f"RVA {rva:#x} not in any section")


def read_cstr(data, off):
    end = data.index(b"\x00", off)
    return data[off:end].decode("ascii", errors="strict")


def main():
    sysroot = os.environ.get("SystemRoot", r"C:\Windows")
    dll_path = os.path.join(sysroot, "System32", "winmm.dll")
    with open(dll_path, "rb") as f:
        data = f.read()

    if data[:2] != b"MZ":
        raise RuntimeError("Not a PE file")
    e_lfanew = struct.unpack_from("<I", data, 0x3C)[0]
    if data[e_lfanew:e_lfanew + 4] != b"PE\x00\x00":
        raise RuntimeError("Invalid PE signature")

    coff_off = e_lfanew + 4
    _, num_sections, _, _, _, opt_size, _ = struct.unpack_from("<HHIIIHH", data, coff_off)
    opt_off = coff_off + 20
    magic = struct.unpack_from("<H", data, opt_off)[0]
    if magic != 0x20B:
        raise RuntimeError(f"Expected PE32+ (0x20B), got {magic:#x}")

    exp_rva, exp_size = struct.unpack_from("<II", data, opt_off + 112)
    sec_off = opt_off + opt_size
    sections = []
    for i in range(num_sections):
        base = sec_off + i * 40
        vsize, va, raw_size, raw_ptr = struct.unpack_from("<IIII", data, base + 8)
        sections.append((va, vsize, raw_size, raw_ptr))

    exp_off = rva_to_off(sections, exp_rva)
    (_, _, _, _, _, ord_base, num_funcs, num_names,
     addr_funcs_rva, addr_names_rva, addr_ords_rva) = struct.unpack_from("<IIHHIIIIIII", data, exp_off)

    funcs_off = rva_to_off(sections, addr_funcs_rva)
    names_off = rva_to_off(sections, addr_names_rva)
    ords_off = rva_to_off(sections, addr_ords_rva)

    idx_to_name = {}
    for i in range(num_names):
        name_rva = struct.unpack_from("<I", data, names_off + i * 4)[0]
        func_idx = struct.unpack_from("<H", data, ords_off + i * 2)[0]
        idx_to_name[func_idx] = read_cstr(data, rva_to_off(sections, name_rva))

    exports = []
    time_begin_ord = None
    for idx in range(num_funcs):
        func_rva = struct.unpack_from("<I", data, funcs_off + idx * 4)[0]
        if func_rva == 0:
            continue
        ordinal = ord_base + idx
        name = idx_to_name.get(idx)
        if name == "timeBeginPeriod":
            time_begin_ord = ordinal
            continue
        exports.append((ordinal, name))

    if time_begin_ord is None:
        raise RuntimeError("timeBeginPeriod not found in winmm.dll")

    here = os.path.dirname(os.path.abspath(__file__))

    inc_lines = [
        "/* Auto-generated by gen_winmm_proxy.py -- do not edit by hand. */",
        f"#define WINMM_STUB_COUNT {len(exports)}",
        "typedef struct { uint16_t ordinal; const char *name; } WinmmExportEntry;",
        "static const WinmmExportEntry g_winmm_exports[WINMM_STUB_COUNT] = {",
    ]
    for ord_val, name in exports:
        c_name = f'"{name}"' if name else "NULL"
        inc_lines.append(f"    {{{ord_val}, {c_name}}},")
    inc_lines.append("};")
    with open(os.path.join(here, "winmm_exports.inc"), "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(inc_lines) + "\n")

    asm_lines = [
        "/* Auto-generated x86-64 forwarding thunks for winmm.dll */",
        ".text",
        ".extern g_winmm_procs",
    ]
    for i in range(len(exports)):
        asm_lines.append(f".global winmm_stub_{i}")
        asm_lines.append(f"winmm_stub_{i}:")
        asm_lines.append(f"    jmp *(g_winmm_procs + {i * 8})(%rip)")
    with open(os.path.join(here, "winmm_stubs.S"), "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(asm_lines) + "\n")

    def_lines = [
        "LIBRARY winmm",
        "EXPORTS",
        f"    timeBeginPeriod = proxy_timeBeginPeriod @{time_begin_ord}",
    ]
    for i, (ord_val, name) in enumerate(exports):
        if name:
            def_lines.append(f"    {name} = winmm_stub_{i} @{ord_val}")
        else:
            def_lines.append(f"    winmm_noname_{ord_val} = winmm_stub_{i} @{ord_val} NONAME")
    with open(os.path.join(here, "winmm.def"), "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(def_lines) + "\n")

    print(f"Generated {len(exports)} stubs + timeBeginPeriod@{time_begin_ord} from {dll_path}")


if __name__ == "__main__":
    main()
